    "p-value","16 paired cases","No conclusive difference");
rows(end+1)=append("Computational profile","25% feature extraction time", ...
    quarterWindow.FeatureExtractionMillisecondsPerRecord,"ms per record", ...
    "146 records; median of 3 timed passes","MATLAB desktop measurement");
