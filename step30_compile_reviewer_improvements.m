    'area',area,'endpoint',endpoint,'value',value,'unit',unit,'n',n,'note',note);
rows=repmat(append("","",0,"","",""),0,1);

fullWindow=early(early.StableWindowFraction==1,:);
halfWindow=early(early.StableWindowFraction==0.5,:);
quarterWindow=early(early.StableWindowFraction==0.25,:);
quarterStat=earlyStats(earlyStats.ComparatorFraction==0.25,:);
halfStat=earlyStats(earlyStats.ComparatorFraction==0.5,:);
combinedFault=randomFault(randomFault.Dataset=="Combined",:);
nuaaFault=randomFault(randomFault.Dataset=="NUAA",:);
