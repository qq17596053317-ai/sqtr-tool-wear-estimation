    phmConclusion.RepeatedWearTimestampBoundaryN,"boundaries","3 cutters", ...
    "Evidence that label-change grouping would merge distinct cuts");

for rowIndex=1:numel(rows)
    EvidenceArea(rowIndex,1)=rows(rowIndex).area;
    Endpoint(rowIndex,1)=rows(rowIndex).endpoint;
    Value(rowIndex,1)=rows(rowIndex).value;
    Unit(rowIndex,1)=rows(rowIndex).unit;
    IndependentUnit(rowIndex,1)=rows(rowIndex).n;
    Interpretation(rowIndex,1)=rows(rowIndex).note;
end
master=table(EvidenceArea,Endpoint,Value,Unit,IndependentUnit,Interpretation);
writetable(master,fullfile(resultDir,'reviewer_improvement_master_summary.csv'));

