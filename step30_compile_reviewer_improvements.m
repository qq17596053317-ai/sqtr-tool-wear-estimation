    combinedFault.BootstrapCIUpper,"relative MAE","12 experiment clusters", ...
    "Automatic gate minus full sensors");
rows(end+1)=append("Randomized multi-fault","NUAA relative MAE improvement", ...
    nuaaFault.RelativeImprovementPercent,"percent","9 independent experiments", ...
    "8/9 units improved");
rows(end+1)=append("Randomized multi-fault","PHM2010 relative MAE improvement", ...
    phmFault.RelativeImprovementPercent,"percent","3 independent cutters", ...
    "2/3 units improved; small-n result not significant");

rows(end+1)=append("PHM segmentation","Cuts detected per cutter", ...
    min(phmAudit.TimestampRunCount),"cuts per cutter","3 cutters", ...
    "Matches the 315-cut protocol for c1, c4, and c6");
