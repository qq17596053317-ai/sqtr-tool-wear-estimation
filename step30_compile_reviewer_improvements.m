    combinedFault.RelativeImprovementPercent,"percent", ...
    "12 independent experiments/cutters; 30 technical repeats averaged", ...
    "Random location, duration, direction, and severity");
rows(end+1)=append("Randomized multi-fault","Combined Holm-adjusted p", ...
    combinedFault.HolmAdjustedP,"p-value","12 paired independent units", ...
    "Multiplicity controlled across NUAA, PHM2010, and combined analyses");
rows(end+1)=append("Randomized multi-fault","Combined bootstrap CI lower", ...
    combinedFault.BootstrapCILower,"relative MAE","12 experiment clusters", ...
    "Automatic gate minus full sensors");
