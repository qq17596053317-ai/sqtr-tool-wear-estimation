paperRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
clearvars -except paperRoot;
clc;

%% Predefined severity-stratified response and regret audit
% This analysis is descriptive. The 30 fault randomisations are technical
% repetitions; they do not increase the independent n beyond nine NUAA
% experiments and three PHM tools. Severity bins follow thirds of the
% prespecified injection ranges and are fixed before inspecting outcomes.

resultDir = fullfile(fileparts(mfilename('fullpath')), 'results');
if ~exist(resultDir, 'dir'); mkdir(resultDir); end
sourceMat = fullfile(paperRoot,'targeted_reviewer_experiments', ...
    'response_regret_audit','results','randomized_fault_robustness.mat');
S = load(sourceMat,'recordTable');
T = S.recordTable;

severityBin = strings(height(T),1);
faults = unique(T.FaultType,'stable');
for f = 1:numel(faults)
    mask = T.FaultType == faults(f);
    if faults(f)=="Saturation" || faults(f)=="Dropout"
        edges = [0.10,0.30,0.50,0.7000001];
    elseif faults(f)=="Bias"
        edges = [0.50,0.50+(3.00-0.50)/3,0.50+2*(3.00-0.50)/3,3.0000001];
    elseif faults(f)=="Noise"
        edges = [0.25,0.25+(2.00-0.25)/3,0.25+2*(2.00-0.25)/3,2.0000001];
    else
        error('Unexpected fault type: %s',faults(f));
    end
    localBin = discretize(T.Severity(mask),edges);
    labels = ["Low","Medium","High"];
    severityBin(mask) = labels(localBin);
end
assert(all(strlength(severityBin)>0),'Every record must receive a severity bin.');
T.SeverityBin = categorical(severityBin,["Low","Medium","High"],'Ordinal',true);

datasets = unique(T.Dataset,'stable');
binLabels = ["Low","Medium","High"];
summaryRows = {};
unitRows = {};
summaryRow = 0; unitRow = 0;
for d = 1:numel(datasets)
    sensors = unique(T.TargetSensor(T.Dataset==datasets(d)),'stable');
    experiments = unique(T.Experiment(T.Dataset==datasets(d)),'stable');
    for s = 1:numel(sensors)
        for f = 1:numel(faults)
            for b = 1:numel(binLabels)
                mask = T.Dataset==datasets(d) & T.TargetSensor==sensors(s) & ...
                    T.FaultType==faults(f) & string(T.SeverityBin)==binLabels(b);
                if ~any(mask); continue; end
                responseMeans = [mean(T.FullAbsoluteError(mask)), ...
                    mean(T.DetectorGuidedMedianAbsoluteError(mask)), ...
                    mean(T.DetectorGuidedMaskAbsoluteError(mask)), ...
                    mean(T.SQTRAbsoluteError(mask))];
                responseNames = ["Fixed","Median","MaskDropout","SQTR"];
                [~,bestResponseIndex] = min(responseMeans);
                summaryRow = summaryRow + 1;
                summaryRows(summaryRow,:) = {datasets(d),sensors(s),faults(f), ...
                    binLabels(b),sum(mask),numel(experiments),30, ...
                    mean(T.DurationFraction(mask)),mean(T.Severity(mask)), ...
                    responseMeans(1),responseMeans(2),responseMeans(3), ...
                    responseMeans(4),responseNames(bestResponseIndex), ...
                    mean(T.OracleMinimumAbsoluteError(mask)), ...
                    mean(T.SQTRRegret(mask)),mean(T.CorrectDetection(mask)), ...
                    mean(T.DetectorMiss(mask)),mean(T.WrongChannelDetection(mask)), ...
                    mean(T.OracleBestAction(mask)=="Full"), ...
                    mean(T.OracleBestAction(mask)=="TargetMedian"), ...
                    mean(T.OracleBestAction(mask)=="TargetMask"), ...
                    mean(T.OracleBestAction(mask)=="TargetExclusion")};

                for e = 1:numel(experiments)
                    unitMask = mask & T.Experiment==experiments(e);
                    if ~any(unitMask); continue; end
                    unitRow = unitRow + 1;
                    unitRows(unitRow,:) = {datasets(d),experiments(e),sensors(s), ...
                        faults(f),binLabels(b),sum(unitMask),30, ...
                        mean(T.FullAbsoluteError(unitMask)), ...
                        mean(T.DetectorGuidedMedianAbsoluteError(unitMask)), ...
                        mean(T.DetectorGuidedMaskAbsoluteError(unitMask)), ...
                        mean(T.SQTRAbsoluteError(unitMask)), ...
                        mean(T.OracleMinimumAbsoluteError(unitMask)), ...
                        mean(T.SQTRRegret(unitMask)), ...
                        mean(T.CorrectDetection(unitMask)), ...
                        mean(T.DetectorMiss(unitMask)), ...
                        mean(T.WrongChannelDetection(unitMask))};
                end
            end
        end
    end
end

summaryTable = cell2table(summaryRows,'VariableNames', ...
    {'Dataset','TargetSensor','FaultType','SeverityBin','RecordScenarioRows', ...
    'IndependentUnitN','TechnicalRepeatN','MeanDurationFraction','MeanSeverity', ...
    'FixedMAE','DetectorGuidedMedianMAE','DetectorGuidedMaskMAE','SQTR_MAE', ...
    'BestDeployableResponse','OracleEnvelopeMAE','MeanSQTRRegret', ...
    'CorrectDetectionRate','MissRate','WrongChannelRate','OracleFullFraction', ...
    'OracleMedianFraction','OracleMaskFraction','OracleExclusionFraction'});

unitTable = cell2table(unitRows,'VariableNames', ...
    {'Dataset','Experiment','TargetSensor','FaultType','SeverityBin', ...
    'RecordScenarioRows','TechnicalRepeatN','FixedMAE', ...
    'DetectorGuidedMedianMAE','DetectorGuidedMaskMAE','SQTR_MAE', ...
    'OracleEnvelopeMAE','MeanSQTRRegret','CorrectDetectionRate','MissRate', ...
    'WrongChannelRate'});

writetable(summaryTable,fullfile(resultDir,'severity_action_summary.csv'));
writetable(unitTable,fullfile(resultDir,'severity_action_units.csv'));
save(fullfile(resultDir,'severity_action_map.mat'),'summaryTable','unitTable');
disp(summaryTable(:,{'Dataset','TargetSensor','FaultType','SeverityBin', ...
    'BestDeployableResponse','CorrectDetectionRate','MeanSQTRRegret'}));

