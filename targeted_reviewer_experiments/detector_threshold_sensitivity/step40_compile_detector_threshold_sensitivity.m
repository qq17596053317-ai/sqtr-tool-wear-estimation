paperRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
clearvars -except paperRoot;
clc;

rootDir = fileparts(mfilename('fullpath'));
resultDir = fullfile(rootDir,'compiled_results');
if ~exist(resultDir,'dir'); mkdir(resultDir); end

floors = [3 4 5];
quantiles = [97.5 99 99.5];
rows = cell(numel(floors)*numel(quantiles)*3,15);
detectionRows = {};
row = 0; detectionRow = 0;
for f = 1:numel(floors)
    for q = 1:numel(quantiles)
        folder = fullfile(rootDir,sprintf('floor%d_q%s',floors(f), ...
            strrep(sprintf('%.1f',quantiles(q)),'.','p')));
        config = readtable(fullfile(folder,'random_fault_configuration.csv'), ...
            'VariableNamingRule','preserve');
        stats = readtable(fullfile(folder,'random_fault_statistics.csv'), ...
            'VariableNamingRule','preserve');
        experiments = readtable(fullfile(folder,'random_fault_experiment_means.csv'), ...
            'VariableNamingRule','preserve');
        detection = readtable(fullfile(folder,'random_fault_detection_summary.csv'), ...
            'VariableNamingRule','preserve');
        statsDataset = string(stats.Dataset);
        experimentDataset = string(experiments.Dataset);
        detectionDataset = string(detection.Dataset);
        detectionSensor = string(detection.TargetSensor);
        detectionFault = string(detection.FaultType);
        for s = 1:height(stats)
            if statsDataset(s)=="Combined"
                cleanTrigger = mean(experiments.CleanTriggerRate);
            else
                cleanTrigger = mean(experiments.CleanTriggerRate( ...
                    experimentDataset==statsDataset(s)));
            end
            row = row + 1;
            rows(row,:) = {config.DetectorFloor(1),config.DetectorQuantile(1), ...
                statsDataset(s),stats.IndependentUnitN(s), ...
                stats.TechnicalRepeatN(s),cleanTrigger, ...
                stats.FullRelativeMAE(s),stats.AutoRelativeMAE(s), ...
                stats.MeanPairedDifference(s),stats.RelativeImprovementPercent(s), ...
                stats.UnitsImproved(s),stats.UnitsWorsened(s), ...
                stats.BootstrapCILower(s),stats.BootstrapCIUpper(s), ...
                stats.HolmAdjustedP(s)};
        end
        for d = 1:height(detection)
            detectionRow = detectionRow + 1;
            detectionRows(detectionRow,:) = {config.DetectorFloor(1), ...
                config.DetectorQuantile(1),detectionDataset(d), ...
                detectionSensor(d),detectionFault(d), ...
                detection.TechnicalRepeatN(d), ...
                detection.MeanCorrectDetectionRate(d), ...
                detection.SDCorrectDetectionRate(d), ...
                detection.MeanMAEImprovementPercent(d)};
        end
    end
end

summaryTable = cell2table(rows,'VariableNames', ...
    {'DetectorFloor','DetectorQuantile','Dataset','IndependentUnitN', ...
    'TechnicalRepeatN','MeanCleanTriggerRate','FullRelativeMAE','SQTRRelativeMAE', ...
    'SQTRMinusFixed','RelativeImprovementPercent','UnitsImproved','UnitsWorsened', ...
    'BootstrapCI_Lower','BootstrapCI_Upper','HolmAdjustedP'});
detectionTable = cell2table(detectionRows,'VariableNames', ...
    {'DetectorFloor','DetectorQuantile','Dataset','TargetSensor','FaultType', ...
    'TechnicalRepeatN','MeanCorrectDetectionRate','SDCorrectDetectionRate', ...
    'MeanMAEImprovementPercent'});
summaryTable.Dataset = string(summaryTable.Dataset);
detectionTable.Dataset = string(detectionTable.Dataset);
detectionTable.TargetSensor = string(detectionTable.TargetSensor);
detectionTable.FaultType = string(detectionTable.FaultType);

combined = summaryTable(summaryTable.Dataset=="Combined",:);
defaultMask = combined.DetectorFloor==4 & combined.DetectorQuantile==99;
assert(sum(defaultMask)==1,'Default threshold setting was not found.');
defaultRow = combined(defaultMask,:);
stabilityTable = table( ...
    min(combined.SQTRRelativeMAE),max(combined.SQTRRelativeMAE), ...
    range(combined.SQTRRelativeMAE), ...
    min(combined.MeanCleanTriggerRate),max(combined.MeanCleanTriggerRate), ...
    defaultRow.SQTRRelativeMAE,defaultRow.MeanCleanTriggerRate, ...
    'VariableNames',{'MinimumSQTRRelativeMAE','MaximumSQTRRelativeMAE', ...
    'SQTRRelativeMAERange','MinimumCleanTriggerRate','MaximumCleanTriggerRate', ...
    'DefaultSQTRRelativeMAE','DefaultCleanTriggerRate'});

writetable(summaryTable,fullfile(resultDir,'detector_threshold_grid_summary.csv'));
writetable(detectionTable,fullfile(resultDir,'detector_threshold_grid_detection.csv'));
writetable(stabilityTable,fullfile(resultDir,'detector_threshold_grid_stability.csv'));
save(fullfile(resultDir,'detector_threshold_grid_results.mat'), ...
    'summaryTable','detectionTable','stabilityTable');

disp(combined(:,{'DetectorFloor','DetectorQuantile','MeanCleanTriggerRate', ...
    'SQTRRelativeMAE','RelativeImprovementPercent'}));
disp(stabilityTable);
