%% Local function: nested random gate and lambda selection
function [testPredictionAll,testPredictionQuality, ...
    testPredictionGated,bestGateThreshold] = ...
    randomGatedRidgePrediction( ...
    XAll,XQuality,qualityRatio,y,outerTrainMask,outerTestMask, ...
    lambdaGrid,numberOfInnerFolds,gateThresholdGrid)

outerTrainingIndex = find(outerTrainMask);
innerCV = cvpartition(numel(outerTrainingIndex), ...
    "KFold",numberOfInnerFolds);

[testPredictionAll,innerPredictionAll] = ...
    randomBranchPredictionAndOOF( ...
    XAll,y,outerTrainMask,outerTestMask,lambdaGrid,innerCV);

[testPredictionQuality,innerPredictionQuality] = ...
    randomBranchPredictionAndOOF( ...
    XQuality,y,outerTrainMask,outerTestMask,lambdaGrid,innerCV);

validationMAE = nan(numel(gateThresholdGrid),1);
for thresholdIndex = 1:numel(gateThresholdGrid)
    innerGatedPrediction = innerPredictionAll;
    switchMask = outerTrainMask & ...
        qualityRatio >= gateThresholdGrid(thresholdIndex);
    innerGatedPrediction(switchMask) = ...
        innerPredictionQuality(switchMask);
    validationMAE(thresholdIndex) = mean(abs( ...
        innerGatedPrediction(outerTrainMask)-y(outerTrainMask)));
end

minimumMAE = min(validationMAE);
candidateIndices = find(validationMAE <= minimumMAE + ...
    1e-12*max(1,abs(minimumMAE)));
[~,tieIndex] = max(gateThresholdGrid(candidateIndices));
bestIndex = candidateIndices(tieIndex);
bestGateThreshold = gateThresholdGrid(bestIndex);

testPredictionGated = testPredictionAll;
testSwitchMask = qualityRatio(outerTestMask) >= bestGateThreshold;
testPredictionGated(testSwitchMask) = ...
    testPredictionQuality(testSwitchMask);

end


%% Local function: random-fold branch selection and OOF predictions
function [testPrediction,bestInnerPrediction] = ...
    randomBranchPredictionAndOOF( ...
    X,y,outerTrainMask,outerTestMask,lambdaGrid,innerCV)

outerTrainingIndex = find(outerTrainMask);
validationMAE = nan(numel(lambdaGrid),1);
allInnerPredictions = nan(numel(y),numel(lambdaGrid));

for lambdaIndex = 1:numel(lambdaGrid)
    currentLambda = lambdaGrid(lambdaIndex);
    innerPrediction = nan(size(y));

    for innerFold = 1:innerCV.NumTestSets
        innerTrainingLocal = training(innerCV,innerFold);
        innerValidationLocal = test(innerCV,innerFold);
        innerTrainingIndex = outerTrainingIndex(innerTrainingLocal);
        innerValidationIndex = outerTrainingIndex(innerValidationLocal);

        innerPrediction(innerValidationIndex) = localFitRidge( ...
            X(innerTrainingIndex,:),y(innerTrainingIndex), ...
            X(innerValidationIndex,:),currentLambda);
    end

    allInnerPredictions(:,lambdaIndex) = innerPrediction;
    validationMAE(lambdaIndex) = mean(abs( ...
        y(outerTrainingIndex)-innerPrediction(outerTrainingIndex)));
end

[~,bestIndex] = min(validationMAE);
bestLambda = lambdaGrid(bestIndex);
bestInnerPrediction = allInnerPredictions(:,bestIndex);
testPrediction = localFitRidge(X(outerTrainMask,:),y(outerTrainMask), ...
    X(outerTestMask,:),bestLambda);

end

%% Local function: ridge regression
function prediction = localFitRidge( ...
    XTraining,yTraining,XTest,lambda)

featureMean = mean(XTraining,1);
featureStandardDeviation = std(XTraining,0,1);

validFeatureMask = ...
    featureStandardDeviation > 1e-12;

XTraining = XTraining(:,validFeatureMask);
XTest = XTest(:,validFeatureMask);

featureMean = ...
    featureMean(validFeatureMask);

featureStandardDeviation = ...
    featureStandardDeviation(validFeatureMask);

XTraining = ...
    (XTraining-featureMean)./ ...
    featureStandardDeviation;

XTest = ...
    (XTest-featureMean)./ ...
    featureStandardDeviation;

responseMean = mean(yTraining);
centeredResponse = yTraining-responseMean;

numberOfFeatures = size(XTraining,2);

coefficient = ...
    (XTraining'*XTraining + ...
    lambda*eye(numberOfFeatures)) \ ...
    (XTraining'*centeredResponse);

prediction = ...
    responseMean + XTest*coefficient;

end
