paperRoot = fileparts(mfilename('fullpath'));
clear;
clc;
close all;

%% 1. Load data
resultFolder = ...
    fullfile(paperRoot, 'mill', 'results');

timeData = load(fullfile( ...
    resultFolder, ...
    "quality_aware_with_time.mat"));

locoData = load(fullfile( ...
    resultFolder, ...
    "time_model_results.mat"));

T = timeData.timeAwareTable;
locoPredictionTable = locoData.predictionTable;

assert(isequal( ...
    T.OriginalIndex, ...
    locoPredictionTable.OriginalIndex), ...
    "The data orders are inconsistent.");

%% 2. Basic variables
y = T.VB;
caseID = T.CaseID;
nSamples = height(T);

elapsedTime = T.ElapsedTime;
elapsedTimeSquared = elapsedTime.^2;

saturationRatio = ...
    T.smcDC_SaturationRatio;

XProcess = T{:,{'DOC','Feed','Material'}};

allVariableNames = ...
    string(T.Properties.VariableNames);

% The original 78 sensor features
sensorVariableNames = ...
    allVariableNames(8:85);

smcDCMask = startsWith( ...
    sensorVariableNames,"smcDC_");

otherSensorNames = ...
    sensorVariableNames(~smcDCMask);

XAllSensors = ...
    T{:,cellstr(sensorVariableNames)};

XOtherSensors = ...
    T{:,cellstr(otherSensorNames)};

%% 3. Time-augmented branches
XAllSensorsTime = [ ...
    XProcess, ...
    XAllSensors, ...
    elapsedTime, ...
    elapsedTimeSquared];

XQualityAwareTime = [ ...
    XProcess, ...
    XOtherSensors, ...
    elapsedTime, ...
    elapsedTimeSquared];

fprintf("AllSensorsTime dimension: %d\n", ...
    size(XAllSensorsTime,2));

fprintf("QualityAwareTime dimension: %d\n", ...
    size(XQualityAwareTime,2));

%% 4. LOCO result
predLOCO = ...
    locoPredictionTable.PredTimeGated;

locoResidual = predLOCO-y;

locoMAE = mean(abs(locoResidual));
locoRMSE = sqrt(mean(locoResidual.^2));

locoR2 = 1- ...
    sum(locoResidual.^2)/ ...
    sum((y-mean(y)).^2);

%% 5. Repeated random five-fold validation
numberOfRepeats = 20;
numberOfOuterFolds = 5;
numberOfInnerFolds = 5;

lambdaGrid = logspace(-4,4,17);
gateThresholdGrid = [0.01 0.10 0.50];

randomMAE = nan(numberOfRepeats,1);
randomRMSE = nan(numberOfRepeats,1);
randomR2 = nan(numberOfRepeats,1);
caseOverlapRate = nan(numberOfRepeats,1);

allRandomPredictions = ...
    nan(nSamples,numberOfRepeats);

selectedGateThresholds = ...
    nan(numberOfRepeats,numberOfOuterFolds);

for repeatIndex = 1:numberOfRepeats

    fprintf( ...
        "\nRandom validation repeat %d/%d\n", ...
        repeatIndex,numberOfRepeats);

    rng(20260716+repeatIndex,"twister");

    outerCV = cvpartition( ...
        nSamples,"KFold",numberOfOuterFolds);

    predAllBranch = nan(nSamples,1);
    predQualityBranch = nan(nSamples,1);
    predRandomGated = nan(nSamples,1);

    overlapCount = 0;

    for foldIndex = 1:numberOfOuterFolds

        fprintf("  Outer fold %d/%d\n", ...
            foldIndex,numberOfOuterFolds);

        outerTrainMask = ...
            training(outerCV,foldIndex);

        outerTestMask = ...
            test(outerCV,foldIndex);

        % Calculate case overlap
        trainingCases = ...
            unique(caseID(outerTrainMask));

        overlapCount = overlapCount + ...
            sum(ismember( ...
            caseID(outerTestMask), ...
            trainingCases));

        % Both lambdas and the gate threshold are selected from this
        % outer fold's training records only.
        [predAllBranch(outerTestMask), ...
            predQualityBranch(outerTestMask), ...
            predRandomGated(outerTestMask), ...
            selectedGateThresholds(repeatIndex,foldIndex)] = ...
            randomGatedRidgePrediction( ...
            XAllSensorsTime,XQualityAwareTime, ...
            saturationRatio,y,outerTrainMask,outerTestMask, ...
            lambdaGrid,numberOfInnerFolds,gateThresholdGrid);
    end

    allRandomPredictions(:,repeatIndex) = ...
        predRandomGated;

    residual = predRandomGated-y;

    randomMAE(repeatIndex) = ...
        mean(abs(residual));

    randomRMSE(repeatIndex) = ...
        sqrt(mean(residual.^2));

    randomR2(repeatIndex) = ...
        1-sum(residual.^2)/ ...
        sum((y-mean(y)).^2);

    caseOverlapRate(repeatIndex) = ...
        overlapCount/nSamples;
end

%% 6. Overall comparison
ValidationScheme = [ ...
    "Leave-One-Case-Out"; ...
    "Repeated Random 5-Fold"];

MAEMean = [ ...
