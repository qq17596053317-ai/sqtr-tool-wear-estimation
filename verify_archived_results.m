function verify_archived_results
%VERIFY_ARCHIVED_RESULTS Check the archived source tables against manuscript values.
root = fileparts(mfilename('fullpath'));

t = readtable(fullfile(root,'mill','results','time_model_overall.csv'), ...
    'TextType','string');
assertClose(t.MAE(t.Model=="TimeGated"), 0.108772765115727, 1e-12, ...
    'NASA SQTR pooled MAE');

v = readtable(fullfile(root,'mill','results','random_vs_grouped_overall.csv'), ...
    'TextType','string');
assertClose(v.MAEMean(v.ValidationScheme=="Repeated Random 5-Fold"), ...
    0.0953662708181688, 1e-12, 'record-wise five-fold mean MAE');
assertClose(v.MeanCaseOverlapRate(v.ValidationScheme=="Repeated Random 5-Fold"), ...
    0.991095890410959, 1e-12, 'train-test case overlap');

r = readtable(fullfile(root,'additional_validation_results', ...
    'reviewer_improvements','random_fault_statistics.csv'), ...
    'TextType','string');
assertClose(r.RelativeImprovementPercent(r.Dataset=="Combined"), ...
    22.2364871189735, 1e-10, 'combined randomised-degradation improvement');
assertClose(r.HolmAdjustedP(r.Dataset=="Combined"), ...
    0.0146484375, 1e-12, 'combined Holm-adjusted p value');

g = readtable(fullfile(root,'multifault_robustness_results', ...
    'multifault_statistics.csv'),'TextType','string');
assertClose(g.FullRelativeMAE(g.Dataset=="Combined"), ...
    1.37449913247599, 1e-12, 'fixed-grid full-model relative MAE');
assertClose(g.AutoRelativeMAE(g.Dataset=="Combined"), ...
    1.08624738726308, 1e-12, 'fixed-grid automatic-routing relative MAE');
assertClose(g.OracleRelativeMAE(g.Dataset=="Combined"), ...
    1.05255721401970, 1e-12, 'fixed-grid oracle relative MAE');

h = readtable(fullfile(root,'targeted_reviewer_experiments', ...
    'high_wear_underestimation','high_wear_threshold_metrics.csv'), ...
    'TextType','string');
mask = h.Model=="PrimaryTimeGated" & h.ActualWearThreshold==0.4;
assertClose(h.MAE(mask), 0.162860298700978, 1e-12, ...
    'record-weighted MAE for VB >= 0.40 mm');

fprintf('All archived-result checks passed.\n');
end

function assertClose(actual, expected, tolerance, label)
assert(isscalar(actual) && isfinite(actual), '%s is missing or non-scalar.', label);
assert(abs(actual-expected) <= tolerance, ...
    '%s differs: observed %.16g, expected %.16g.', label, actual, expected);
end
